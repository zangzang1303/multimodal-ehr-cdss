

import re
import difflib
from typing import List, Dict, Any, Optional, Tuple


class EvidenceGrounder:
    """
    Evidence Grounding Engine for Clinical Notes.
    Maps statements/claims generated by LLM onto character offsets [start, end]
    in the active de-identified clinical note.

    GHI CHÚ HỢP ĐỒNG GIAO DIỆN (DÀNH CHO MEMBER 3 - EvidenceViewer.tsx):
    - Đảm bảo bất biến 100%: note.slice(span.start, span.end) === span.text.
    - Hàm resolve_overlapping_spans() đã loại bỏ các span đè nhau, đảm bảo an toàn
      khi bọc thẻ <mark> highlight trên React mà không bao giờ bị lỗi lồng thẻ HTML.
    - Các claim bị LLM bịa đặt (không có trong bệnh án) sẽ có status="unverified",
      spans=[] để Frontend hiển thị cảnh báo không thể kiểm chứng nguồn gốc.
    """

    def __init__(
        self,
        fuzzy_threshold: float = 0.88,
        min_claim_length: int = 5,
        max_sliding_window_slack: int = 15,
    ):
       
        self.fuzzy_threshold = fuzzy_threshold
        self.min_claim_length = min_claim_length
        self.max_sliding_window_slack = max_sliding_window_slack

    def ground_evidence(
        self,
        deidentified_note: str,
        claims: List[str],
        allow_fuzzy_proposal: bool = False,
    ) -> List[Dict[str, Any]]:
        
        if not deidentified_note or not claims:
            return []

        verified_spans: List[Dict[str, Any]] = []

        for raw_claim in claims:
            if not isinstance(raw_claim, str):
                continue
            claim = raw_claim.strip()
            if len(claim) < self.min_claim_length:
                continue

          
            exact_spans = self._find_exact_matches(deidentified_note, claim)
            if exact_spans:
                verified_spans.extend(exact_spans)
                continue

            
            ci_spans = self._find_case_insensitive_matches(deidentified_note, claim)
            if ci_spans:
                verified_spans.extend(ci_spans)
                continue

          
            norm_spans = self._find_normalized_matches(deidentified_note, claim)
            if norm_spans:
                verified_spans.extend(norm_spans)
                continue

          
            if allow_fuzzy_proposal:
                fuzzy_candidate = self._find_fuzzy_candidate(deidentified_note, claim)
                if fuzzy_candidate:
                    verified_spans.append(fuzzy_candidate)

        return self.resolve_overlapping_spans(verified_spans)

    def ground_claims_detailed(
        self,
        deidentified_note: str,
        claims: List[str],
    ) -> List[Dict[str, Any]]:
        
        results = []
        for raw_claim in claims:
            if not isinstance(raw_claim, str) or not raw_claim.strip():
                results.append({
                    "claim": str(raw_claim),
                    "status": "unverified",
                    "spans": [],
                    "confidence": 0.0,
                    "match_type": "none",
                    "reason": "Empty or non-string claim",
                })
                continue

            claim = raw_claim.strip()

           
            exact = self._find_exact_matches(deidentified_note, claim)
            if exact:
                results.append({
                    "claim": claim,
                    "status": "verified",
                    "spans": exact,
                    "confidence": 1.0,
                    "match_type": "exact",
                    "clinical_interpretation_note": "Span location verified. Note: Clinical interpretation must be validated independently.",
                })
                continue

           
            ci = self._find_case_insensitive_matches(deidentified_note, claim)
            if ci:
                results.append({
                    "claim": claim,
                    "status": "verified",
                    "spans": ci,
                    "confidence": 0.95,
                    "match_type": "case_insensitive",
                    "clinical_interpretation_note": "Span location verified (case-insensitive). Clinical interpretation must be validated independently.",
                })
                continue

           
            norm = self._find_normalized_matches(deidentified_note, claim)
            if norm:
                results.append({
                    "claim": claim,
                    "status": "verified",
                    "spans": norm,
                    "confidence": 0.90,
                    "match_type": "normalized",
                    "clinical_interpretation_note": "Span location verified (normalized whitespace). Clinical interpretation must be validated independently.",
                })
                continue

           
            fuzzy = self._find_fuzzy_candidate(deidentified_note, claim)
            if fuzzy and fuzzy["confidence"] >= self.fuzzy_threshold:
                results.append({
                    "claim": claim,
                    "status": "candidate",
                    "spans": [fuzzy],
                    "confidence": fuzzy["confidence"],
                    "match_type": "fuzzy_candidate",
                    "clinical_interpretation_note": "Proposed fuzzy match candidate. Not automatically confirmed as exact evidence.",
                })
                continue

           
            results.append({
                "claim": claim,
                "status": "unverified",
                "spans": [],
                "confidence": 0.0,
                "match_type": "none",
                "reason": "Claim cannot be grounded in active de-identified clinical note.",
            })

        return results

    def _find_exact_matches(self, note: str, claim: str) -> List[Dict[str, Any]]:
      
        spans = []
        start = 0
        while True:
            idx = note.find(claim, start)
            if idx == -1:
                break
            end = idx + len(claim)
            # Invariant check
            assert note[idx:end] == claim, "Invariant violation: note[start:end] != claim"
            spans.append({
                "text": claim,
                "start": idx,
                "end": end,
                "confidence": 1.0,
                "match_type": "exact",
            })
            start = end
        return spans

    def _find_case_insensitive_matches(self, note: str, claim: str) -> List[Dict[str, Any]]:
        
        spans = []
        pattern = re.escape(claim)
        for match in re.finditer(pattern, note, re.IGNORECASE):
            s, e = match.start(), match.end()
            text_in_note = note[s:e]
        
            assert note[s:e] == text_in_note, "Invariant violation: note[s:e] != text"
            spans.append({
                "text": text_in_note,
                "start": s,
                "end": e,
                "confidence": 0.95,
                "match_type": "case_insensitive",
            })
        return spans

    def _find_normalized_matches(self, note: str, claim: str) -> List[Dict[str, Any]]:
    
        spans = []
        tokens = [re.escape(tok) for tok in claim.split()]
        if len(tokens) <= 1:
            return spans
        regex_pattern = r"\s+".join(tokens)
        try:
            for match in re.finditer(regex_pattern, note, re.IGNORECASE):
                s, e = match.start(), match.end()
                text_in_note = note[s:e]
                assert note[s:e] == text_in_note, "Invariant violation"
                spans.append({
                    "text": text_in_note,
                    "start": s,
                    "end": e,
                    "confidence": 0.90,
                    "match_type": "normalized",
                })
        except re.error:
            pass
        return spans

    def _find_fuzzy_candidate(self, note: str, claim: str) -> Optional[Dict[str, Any]]:
    
        claim_len = len(claim)
        if claim_len < self.min_claim_length or len(note) < self.min_claim_length:
            return None

        best_score = 0.0
        best_span: Optional[Tuple[int, int]] = None

       
        window_sizes = [
            claim_len,
            max(self.min_claim_length, claim_len - self.max_sliding_window_slack),
            claim_len + self.max_sliding_window_slack,
        ]

        matcher = difflib.SequenceMatcher(None, b=claim.lower())

        for w_size in set(window_sizes):
            if w_size > len(note):
                continue
            step = max(1, w_size // 4)
            for i in range(0, len(note) - w_size + 1, step):
                chunk = note[i : i + w_size].lower()
                matcher.set_seq1(chunk)
                ratio = matcher.quick_ratio()
                if ratio > best_score:
                    real_ratio = matcher.ratio()
                    if real_ratio > best_score:
                        best_score = real_ratio
                        best_span = (i, i + w_size)

        if best_score >= self.fuzzy_threshold and best_span is not None:
            s, e = best_span
            text_in_note = note[s:e]
            return {
                "text": text_in_note,
                "start": s,
                "end": e,
                "confidence": round(best_score, 3),
                "match_type": "fuzzy_candidate",
            }

        return None

    @staticmethod
    def resolve_overlapping_spans(spans: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    
        if not spans:
            return []

        
        sorted_spans = sorted(
            spans,
            key=lambda x: (x["start"], -x.get("confidence", 1.0), -(x["end"] - x["start"]))
        )

        resolved: List[Dict[str, Any]] = []
        for current in sorted_spans:
            if not resolved:
                resolved.append(current)
                continue

            last = resolved[-1]
          
            if current["start"] < last["end"]:
              
                if current.get("confidence", 0.0) > last.get("confidence", 0.0):
                    resolved[-1] = current
                
                continue
            else:
                resolved.append(current)

        return resolved

