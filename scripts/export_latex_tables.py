"""Generate LaTeX tables and number macros from results/registry.json.

The paper must ``\\input{generated/...}`` these files instead of typing numbers by hand
(Phase 3 rule: one source of truth). Output: docs/paper_latex/generated/*.tex
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "paper_latex" / "generated"

SHORT = {
    "lr_tabular": "Logistic Regression", "catboost": "CatBoost", "ft_transformer": "FT-Transformer",
    "tfidf_lr": "TF-IDF + LR", "bert_frozen": "Bio\\_ClinicalBERT (đóng băng)",
    "bert_ft": "Bio\\_ClinicalBERT (fine-tune)", "concat_frozen": "Concat fusion",
    "xattn_frozen": "\\textbf{Cross-attention (đóng băng)}", "xattn_ft": "Cross-attention (fine-tune)",
    "ensemble_cb_bertft": "Ensemble CatBoost + BERT-FT",
}
GROUP = {"tabular": "Chỉ dữ liệu bảng", "text": "Chỉ văn bản", "fusion": "Dung hợp"}


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def pm(mean, sd):
    return f"{mean:.3f} $\\pm$ {sd:.3f}" if sd else f"{mean:.3f}"


def ci(c):
    return "--" if not c else f"[{c[0]:.3f}; {c[1]:.3f}]"


def pval(p):
    if p is None:
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("% AUTO-GENERATED by scripts/export_latex_tables.py from results/registry.json. "
                            "Do not edit.\n" + body, encoding="utf-8")


def tab_rq1(reg) -> None:
    rq1 = reg["rq1_multiseed_comparison"]
    comps = {c["comparator"]: c for c in rq1["comparisons_vs_deployment_model"]}
    lines = [r"\begin{table}[htbp]\centering\scriptsize",
             r"\caption{RQ1 -- So sánh công bằng trên tập kiểm thử strict ($N=" + str(rq1["test_n"]) + r"$). "
             r"AUROC/F1/ECE: trung bình $\pm$ SD qua seed (xác suất đã hiệu chuẩn nhiệt độ trên validation). "
             r"CI 95\%: bootstrap theo bản ghi ($B=2000$) trên seed có NLL validation thấp nhất -- các bản ghi chung bệnh nhân Synthea gốc nên CI hẹp hơn độ bất định thực. "
             r"$\Delta$: Cross-attention (đóng băng) trừ mô hình so sánh; $p$ hiệu chỉnh Holm.}",
             r"\label{tab:rq1}",
             r"\begin{tabular}{@{}llccccc@{}}\toprule",
             r"Nhóm & Mô hình & AUROC (TB $\pm$ SD, $n$ seed) & AUROC seed đại diện [CI 95\%] & Macro-F1 & ECE & $\Delta$AUROC [CI 95\%], $p_{\text{Holm}}$ \\ \midrule"]
    last = None
    for m in rq1["models"]:
        group = GROUP[m["modality"]] if m["modality"] != last else ""
        if m["modality"] != last and last is not None:
            lines.append(r"\midrule")
        last = m["modality"]
        c = comps.get(m["model"])
        delta = "(tham chiếu)" if m["model"] == "xattn_frozen" else \
            f"{c['delta']:+.3f} {ci(c['ci95'])}, {pval(c['holm_adjusted_p'])}"
        lines.append(f"{group} & {SHORT[m['model']]} & {pm(m['auroc_mean'], m['auroc_sd'])} ({m['n_seeds']}) & "
                     f"{f3(m['auroc_rep_seed'])} {ci(m['auroc_ci95'])} & {pm(m['f1_mean'], m['f1_sd'])} & "
                     f"{f3(m['ece_mean'])} & {delta} \\\\")
    lines += [r"\bottomrule\end{tabular}\end{table}", ""]
    write("tab_rq1.tex", "\n".join(lines))


def tab_rq2(reg) -> None:
    rq2 = reg.get("rq2_text_signal_decomposition")
    if not rq2:
        return
    cols = [("tfidf_lr", "TF-IDF+LR"), ("bert_frozen", "BERT đóng băng"), ("bert_ft", "BERT fine-tune"),
            ("xattn_frozen", "Cross-attention")]
    ref = rq2["tabular_only_reference_auroc"]
    lines = [r"\begin{table}[htbp]\centering\small",
             r"\caption{RQ2 -- Phân rã tín hiệu văn bản: macro AUROC trên test strict theo biến thể ghi chú "
             r"(trung bình 3 seed; TF-IDF tất định). Tham chiếu chỉ dữ liệu bảng: LR " + f3(ref.get("lr_tabular"))
             + r", CatBoost " + f3(ref.get("catboost")) + r".}",
             r"\label{tab:rq2}", r"\begin{tabular}{@{}l" + "c" * len(cols) + r"@{}}\toprule",
             "Biến thể ghi chú & " + " & ".join(c[1] for c in cols) + r" \\ \midrule"]
    for v in rq2["variants"]:
        lines.append(v["label"] + " & " + " & ".join(
            (pm(v[k], v.get(f"{k}_sd")) if v.get(k) is not None else "--") for k, _ in cols) + r" \\")
    lines += [r"\bottomrule\end{tabular}\end{table}", ""]
    write("tab_rq2.tex", "\n".join(lines))


def tab_rq3(reg) -> None:
    rq3 = reg.get("rq3_complementarity_simulation")
    if not rq3:
        return
    lines = [r"\begin{table}[htbp]\centering\small",
             r"\caption{RQ3 -- \textbf{Mô phỏng} bổ trợ có kiểm soát: macro AUROC (trung bình 2 seed). "
             r"$\rho$: tỷ lệ ca có câu triệu chứng đặc hiệu trong ghi chú đã che số; $\sigma$: nhiễu Gauss trên "
             r"biến số (bội số SD). $\Delta$ = cross-attention trừ mô hình đơn phương thức tốt hơn.}",
             r"\label{tab:rq3}", r"\begin{tabular}{@{}cccccc@{}}\toprule",
             r"$\rho$ & $\sigma$ & Bảng & Văn bản & Cross-attention & $\Delta$ \\ \midrule"]
    for g in rq3["grid"]:
        lines.append(f"{g['rho']:.2f} & {g['sigma']:.1f} & {f3(g['tabular'])} & {f3(g['text'])} & "
                     f"{f3(g['cross_attention'])} & {g['delta_xattn_vs_best_unimodal']:+.3f} \\\\")
    lines += [r"\bottomrule\end{tabular}\end{table}", ""]
    write("tab_rq3.tex", "\n".join(lines))


def rq3_text(reg) -> None:
    """Data-driven sentences for RQ3 (direction of the effect is read from the registry)."""
    rq3 = reg.get("rq3_complementarity_simulation")
    if not rq3:
        return
    grid = {(g["rho"], g["sigma"]): g for g in rq3["grid"]}
    rhos = sorted({k[0] for k in grid})
    sigmas = sorted({k[1] for k in grid})
    lo, hi = grid[(rhos[0], sigmas[0])], grid[(rhos[-1], sigmas[-1])]
    best = max(rq3["grid"], key=lambda g: g["delta_xattn_vs_best_unimodal"])
    worst = min(rq3["grid"], key=lambda g: g["delta_xattn_vs_best_unimodal"])
    positive = [g for g in rq3["grid"] if g["delta_xattn_vs_best_unimodal"] > 0.01]
    txt = (f"Khi văn bản không có tín hiệu riêng ($\\rho={rhos[0]:g}$) và dữ liệu bảng không nhiễu ($\\sigma={sigmas[0]:g}$), "
           f"cross-attention đạt {lo['cross_attention']:.3f} so với {max(lo['tabular'], lo['text']):.3f} của mô hình đơn "
           f"phương thức tốt hơn ($\\Delta={lo['delta_xattn_vs_best_unimodal']:+.3f}$). Khi mọi ca có tín hiệu văn bản "
           f"($\\rho={rhos[-1]:g}$) và dữ liệu bảng nhiễu mạnh ($\\sigma={sigmas[-1]:g}$), $\\Delta={hi['delta_xattn_vs_best_unimodal']:+.3f}$. "
           f"$\\Delta$ lớn nhất là {best['delta_xattn_vs_best_unimodal']:+.3f} tại $(\\rho,\\sigma)=({best['rho']:g},{best['sigma']:g})$ "
           f"và nhỏ nhất là {worst['delta_xattn_vs_best_unimodal']:+.3f} tại $({worst['rho']:g},{worst['sigma']:g})$; "
           f"{len(positive)}/{len(rq3['grid'])} cấu hình có $\\Delta>0.01$.")
    write("rq3_text.tex", txt + "\n")
    write("rq3_macros.tex", "\n".join([
        f"\\newcommand{{\\rqthreeBestDelta}}{{{best['delta_xattn_vs_best_unimodal']:+.3f}}}",
        f"\\newcommand{{\\rqthreeBestRho}}{{{best['rho']:g}}}",
        f"\\newcommand{{\\rqthreeBestSigma}}{{{best['sigma']:g}}}",
        f"\\newcommand{{\\rqthreeBaseDelta}}{{{lo['delta_xattn_vs_best_unimodal']:+.3f}}}",
        f"\\newcommand{{\\rqthreePositive}}{{{len(positive)}/{len(rq3['grid'])}}}"]) + "\n")


