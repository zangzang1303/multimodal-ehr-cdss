def tab_generalization(reg) -> None:
    cv = reg.get("sensitivity_grouped_cv_posthoc")
    gen = reg.get("generalization")
    if not cv and not gen:
        return
    lines = [r"\begin{table}[htbp]\centering\small",
             r"\caption{Độ bền nội bộ: (a) 5-fold grouped CV \textbf{post-hoc} trên 2.000 ca (trung bình $\pm$ SD qua "
             r"fold, seed 42); (b) temporal split theo nhóm nguồn (dấu thời gian tổng hợp). Không phải ngoại kiểm.}",
             r"\label{tab:generalization}", r"\begin{tabular}{@{}lccc@{}}\toprule",
             r"Mô hình & (a) Grouped CV & (b) Temporal [CI 95\%] & Strict (cùng seed) \\ \midrule"]
    cv_rows = {m["model"]: m for m in (cv or {}).get("models", [])}
    tmp = (gen or {}).get("by_model", {})
    for key in [k for k in SHORT if k in cv_rows or k in tmp]:
        c, t = cv_rows.get(key), tmp.get(key, {})
        lines.append(f"{SHORT[key]} & {pm(c['auroc_mean'], c['auroc_sd']) if c else '--'} & "
                     f"{f3(t.get('macro_auroc_temporal'))} {ci(t.get('ci95'))} & {f3(t.get('macro_auroc_strict'))} \\\\")
    lines += [r"\bottomrule\end{tabular}\end{table}", ""]
    write("tab_generalization.tex", "\n".join(lines))


def macros(reg) -> None:
    rq1 = {m["model"]: m for m in reg["rq1_multiseed_comparison"]["models"]}
    comps = {c["comparator"]: c for c in reg["rq1_multiseed_comparison"]["comparisons_vs_deployment_model"]}
    out = []

    def add(name, value):
        out.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    letters = {"lr_tabular": "LRTab", "catboost": "CatBoost", "ft_transformer": "FTT", "tfidf_lr": "Tfidf",
               "bert_frozen": "BertFrozen", "bert_ft": "BertFT", "concat_frozen": "Concat",
               "xattn_frozen": "Xattn", "xattn_ft": "XattnFT", "ensemble_cb_bertft": "Ensemble"}
    for key, tag in letters.items():
        if key in rq1:
            add(f"auc{tag}", f"{rq1[key]['auroc_mean']:.3f}")
            add(f"aucsd{tag}", f"{rq1[key]['auroc_sd']:.3f}")
            add(f"ece{tag}", f"{rq1[key]['ece_mean']:.3f}")
        if key in comps:
            c = comps[key]
            add(f"delta{tag}", f"{c['delta']:+.3f}")
            add(f"deltaci{tag}", ci(c["ci95"]))
            add(f"p{tag}", pval(c["holm_adjusted_p"]))
    rq2 = reg.get("rq2_text_signal_decomposition", {}).get("variants", [])
    for v in rq2:
        tag = {"full": "Full", "num_masked": "NumMasked", "no_vitals": "NoVitals", "narrative_only": "Narrative"}[v["variant"]]
        for k, t in (("tfidf_lr", "Tfidf"), ("bert_ft", "BertFT"), ("bert_frozen", "BertFrozen"), ("xattn_frozen", "Xattn")):
            if v.get(k) is not None:
                add(f"rqtwo{t}{tag}", f"{v[k]:.3f}")
    cal = reg["rq4_calibration"]["methods"]
    add("eceUncal", f"{cal['uncalibrated']['ece_10_equal_width']:.3f}")
    add("eceTemp", f"{cal['temperature']['ece_10_equal_width']:.3f}")
    add("deploySeed", str(reg["metadata"]["deployment_seed"]))
    add("testN", str(reg["rq1_multiseed_comparison"]["test_n"]))
    for m in reg.get("sensitivity_grouped_cv_posthoc", {}).get("models", []):
        tag = letters.get(m["model"])
        if tag:
            add(f"cv{tag}", f"{m['auroc_mean']:.3f}")
            add(f"cvsd{tag}", f"{m['auroc_sd']:.3f}")
            add(f"cvmin{tag}", f"{min(m['fold_auroc']):.3f}")
    for k, v in reg.get("generalization", {}).get("by_model", {}).items():
        tag = letters.get(k)
        if tag:
            add(f"tmp{tag}", f"{v['macro_auroc_temporal']:.3f}")
    prov = reg.get("data_provenance", {})
    if prov:
        add("testSourcePatients", str(prov["test"]["distinct_source_patients"]))
        add("allSourcePatients", str(sum(prov[s]["distinct_source_patients"] for s in ("train", "val", "test"))))
    rag = reg.get("rag", {}).get("grounding_audit_50_cases", {})
    if rag:
        add("ragCases", str(rag.get("cases_tested")))
        add("ragClaims", str(rag.get("total_genuine_claims")))
        add("ragGrounded", str(rag.get("grounded_claims")))
        add("ragSpanMatch", f"{rag.get('span_substring_match_rate', 0):.2f}")
        add("ragProbes", f"{rag.get('rejected_out_of_note_probes')}/{rag.get('injected_out_of_note_probes')}")
        add("ragNotesSource", str(rag.get("notes_source_path", "")).replace("_", "\\_"))
    lat = reg.get("latency", {}).get("endpoints", {})
    for ep, tag in (("/api/v1/predict/multimodal", "Multimodal"), ("/api/v1/predict/baseline", "Baseline"),
                    ("/api/v1/agent/explain", "Explain")):
        if ep in lat:
            add(f"latPfifty{tag}", f"{lat[ep]['p50_ms']:.0f}")
            add(f"latPninetyfive{tag}", f"{lat[ep]['p95_ms']:.0f}")
            codes = lat[ep].get("status_codes_observed") or []
            add(f"latStatus{tag}", "/".join(map(str, codes)) or "--")
    if lat:
        add("latMode", str(reg["latency"].get("measurement_mode", "")).replace("_", "\\_"))
        add("latDevice", str(reg["latency"].get("device_info", "")).replace("_", "\\_").replace("|", "--"))
    write("macros.tex", "\n".join(out) + "\n")


def main() -> None:
    reg = json.loads((ROOT / "results" / "registry.json").read_text(encoding="utf-8"))
    for fn in (macros, tab_rq1, tab_rq2, tab_rq3, rq3_text, tab_calibration, tab_robustness, tab_dca, tab_fairness,
               tab_generalization):
        fn(reg)
    print(f"[OK] LaTeX tables written to {OUT}")


if __name__ == "__main__":
    main()
