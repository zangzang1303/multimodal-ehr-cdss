"""Table 1 (baseline characteristics) generated from the canonical strict split.

Writes docs/paper_latex/generated/tab_cohort.tex and results/raw/cohort_table.json.
Values are computed from data/processed_rebuilt_strict (after verify_manifest); missingness
is taken from the *_is_missing indicators created before MICE imputation.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.data_pipeline.manifest import verify_manifest  # noqa: E402

DATA = ROOT / "data" / "processed_rebuilt_strict"
OUT = ROOT / "docs" / "paper_latex" / "generated" / "tab_cohort.tex"
CLASS_NAMES = {0: "Hen", 1: "COPD", 2: "Suy tim", 3: "Viêm phổi"}
CONT = [("age", "Tuổi (năm)", 0), ("systolic_bp", "HA tâm thu (mmHg)", 0), ("diastolic_bp", "HA tâm trương (mmHg)", 0),
        ("heart_rate", "Nhịp tim (/phút)", 0), ("respiratory_rate", "Nhịp thở (/phút)", 0),
        ("temperature", "Thân nhiệt ($^\\circ$C)", 1), ("spo2", "SpO$_2$ (\\%)", 1),
        ("wbc_count", "Bạch cầu ($10^9$/L)", 1), ("crp", "CRP (mg/L)", 1)]


def med_iqr(s: pd.Series, d: int) -> str:
    q1, q2, q3 = s.quantile([0.25, 0.5, 0.75])
    return f"{q2:.{d}f} [{q1:.{d}f}--{q3:.{d}f}]"


def n_pct(mask: pd.Series) -> str:
    return f"{int(mask.sum())} ({100 * mask.mean():.1f}\\%)"


def main() -> None:
    verify_manifest(DATA)
    splits = {s: pd.read_parquet(DATA / f"{s}.parquet") for s in ("train", "val", "test")}
    allrows = pd.concat(splits.values(), ignore_index=True)
    cols = [("Toàn bộ", allrows), ("Train", splits["train"]), ("Val", splits["val"]), ("Test", splits["test"])]
    cols += [(CLASS_NAMES[k], allrows[allrows.diagnosis_label == k]) for k in range(4)]
    rows = [("Nam", lambda d: n_pct(d.gender.astype(str) == "M")),
            ("Đang hút thuốc", lambda d: n_pct(d.smoking_status.astype(str) == "CURRENT")),
            ("Từng hút thuốc", lambda d: n_pct(d.smoking_status.astype(str) == "FORMER")),
            ("Tăng huyết áp", lambda d: n_pct(d.history_hypertension.astype(int) == 1)),
            ("Đái tháo đường", lambda d: n_pct(d.history_diabetes.astype(int) == 1))]
    rows += [(label, (lambda c, dd: (lambda d: med_iqr(d[c], dd)))(c, dd)) for c, label, dd in CONT]
    rows += [(f"Thiếu {lab} trước gán MICE", (lambda c: (lambda d: n_pct(d[f"{c}_is_missing"].astype(int) == 1)))(c))
             for c, lab in (("wbc_count", "WBC"), ("crp", "CRP"))]
    rows += [("Ghi chú dạng MTSamples", lambda d: n_pct(d.clinical_note.str.contains("VITALS AT ADMISSION", regex=False)))]
    header = " & ".join(f"\\textbf{{{name}}}" for name, _ in cols)
    sizes = " & ".join(f"($n={len(d)}$)" for _, d in cols)
    lines = ["% AUTO-GENERATED by scripts/export_cohort_table.py. Do not edit.",
             r"\begin{table}[htbp]\centering\scriptsize",
             r"\caption{Đặc điểm đoàn hệ theo split và theo nhóm chẩn đoán (n (\%) hoặc trung vị [IQR]; giá trị sau gán "
             r"MICE, tỷ lệ thiếu tính từ biến chỉ báo trước gán). Lưu ý tập test có phân bố khác train: toàn bộ ca suy tim "
             r"trong test là nam và không có người đang hút thuốc.}",
             r"\label{tab:cohort_characteristics}",
             r"\begin{tabular}{@{}lcccc|cccc@{}}\toprule",
             "Biến & " + header + r" \\", " & " + sizes + r" \\ \midrule"]
    data = {}
    for label, fn in rows:
        vals = [fn(d) for _, d in cols]
        data[label] = vals
        lines.append(f"{label} & " + " & ".join(vals) + r" \\")
    lines += [r"\bottomrule\end{tabular}\end{table}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    (ROOT / "results" / "raw").mkdir(parents=True, exist_ok=True)
    (ROOT / "results" / "raw" / "cohort_table.json").write_text(
        json.dumps({"columns": [n for n, _ in cols], "rows": data}, ensure_ascii=False, indent=2), encoding="utf-8")
    test = splits["test"]
    hf = test[test.diagnosis_label == 2]
    print(f"[OK] {OUT}  | test HF male: {(hf.gender == 'M').mean():.2f}, test CURRENT smokers: "
          f"{(test.smoking_status == 'CURRENT').sum()}")


if __name__ == "__main__":
    main()
